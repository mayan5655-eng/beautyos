// lib/protocolBook/advanced.ts — the advanced chapters: cosmetic microneedling, RF tightening, the plasma pen and needle-free
// mesotherapy. In the full book, and shown ONLY in the countries listed on each protocol (lib/protocolBook/book.ts canOpen).
//
// ── Why a country switch ────────────────────────────────────────────────────────────────────────────────────────────────
// Owner decision, 2026-11-27: these treatments are part of an Israeli cosmetician's daily practice and belong in the book.
// A regulation check the same day (search summaries only; no source page could be opened) found:
//   * Israel: no law names these treatments and cosmetics is not a licensed profession, so nothing forbids them by name and
//     cosmeticians perform them routinely. The official position is stricter: the State Comptroller (report 69b, 2019)
//     treated skin-perforating mesotherapy as physician-only. Injections are physician-only, which the owner confirms.
//   * Abroad: most markets checked keep microneedling and plasma pens from aestheticians (California, France; Canada
//     authorises plasma pens for health-care professionals only; the FDA has cleared no plasma pen for skin tightening).
// So each protocol carries the list of countries where it is shown: Israel, and the United Kingdom (owner decision the same
// day: the check found that almost nothing is reserved by law there yet; the licensing scheme under the Health and Care Act
// 2022 was confirmed in August 2025 but is not in force. When it comes into force, GB must be re-checked, and may have to
// come off this list). To open another market: check its rules, then add its ISO code to that protocol's `countries`.
// Never add a country on a guess.
//
// ── What these chapters are, and are not ────────────────────────────────────────────────────────────────────────────────
//   * Microneedling: cosmetic depth only (0.25–0.5 mm). Deeper needling is not this protocol.
//   * RF: non-ablative only. RF with needles and fractional RF are not this protocol (FDA safety communication, Oct 2025).
//   * Mesotherapy: NEEDLE-FREE (electroporation). Needle mesotherapy is an injection, and the text says so.
//   * Plasma pen: the highest-risk treatment in the book, and written that way: phototypes I–III only, test spots with a
//     4–6 week wait, never the eyelid margin, scabs never removed.
// Fact-checked 2026-11-27 (search summaries; the reviewer could open no source page). What it changed: the plasma pen no
// longer goes on the eyelids at all, numbing cream and alcohol prep carry their own warnings, microneedling keeps its own
// sterile rule after the session, and several stops were added to each chapter.
