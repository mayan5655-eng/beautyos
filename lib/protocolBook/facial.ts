// Reviewed against the draft book (2026-11-27). What changed from the draft, and why:
//   * Acne: steam after a peel removed. A salicylic peel already softens comedones, and steam on freshly peeled skin
//     only raises irritation. Extractions now follow the peel directly. Salicylate (aspirin) allergy added as a stop.
//     The white film a salicylic peel leaves is crystals, not frost: said so, because mistaking it leads to an
//     over-neutralised or over-layered peel.
//   * Every peel step says how it ends (self-neutralising or neutralised per the manufacturer).
//   * Contraindications are split into "do not treat today" and "treat, but adapt", the way a clinic actually decides.
//   * Each protocol says what is normal afterwards and when to stop on the spot.
//   * Pigmentation: the Wood's lamp is a guide, not a verdict on depth (mixed melasma is common).
//   * Anti-aging: "drink plenty of water the day before" removed (not a protocol step).
// Concentrations are the usual professional ranges; the manufacturer's instructions always win, and the book says so.
