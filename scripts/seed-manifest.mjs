// scripts/seed-manifest.mjs
//
// Writes lib/design/templateSeedManifest.ts: the list of seed images that ACTUALLY EXIST under
// public/defaults/seed/. templateSeedImageUrl() answers null for anything not on it, so a template
// whose seed was never generated shows the clean placeholder instead of a broken-image icon (found
// 2026-10-06: 15 URLs 404'd - every reel scene and one story-only template - because the URL was
// built for every template whether or not a file existed).
//
//   node scripts/seed-manifest.mjs
//
// Run it after generating images (scripts/generate-template-seed-images.ts does). test-seed-manifest.ts
// fails if the manifest and the directory disagree, so forgetting is caught, not shipped.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function seedStemsOnDisk() {
  const dir = path.join(root, 'public', 'defaults', 'seed');
  return fs.existsSync(dir)
    ? fs.readdirSync(dir).filter((f) => f.endsWith('.jpg')).map((f) => f.replace(/\.jpg$/, '')).sort()
    : [];
}

export function writeSeedManifest() {
  const stems = seedStemsOnDisk();
  const body = `// GENERATED by scripts/seed-manifest.mjs - do not edit by hand.
// The seed images that exist under public/defaults/seed/. See templateSeedImages.ts.
export const SEED_STEMS: ReadonlySet<string> = new Set([
${stems.map((s) => `  '${s}',`).join('\n')}
]);
`;
  fs.writeFileSync(path.join(root, 'lib', 'design', 'templateSeedManifest.ts'), body);
  return stems.length;
}

if (process.argv[1] && process.argv[1].endsWith('seed-manifest.mjs')) {
  console.log(`seed manifest: ${writeSeedManifest()} images`);
}
