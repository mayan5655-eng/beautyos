// scripts/import-topic-bank.mjs
//
// One-time (re-run when the source sheet changes) extraction:
// content/imports/templates-365.xlsx -> lib/ai/topicBank.ts.
//
// The source workbook is NOT committed — it's source material, not code, and
// *.xlsx is gitignored for real client data anyway (see .gitignore). Keep
// your own copy at that path to re-run this; lib/ai/topicBank.ts, the actual
// committed deliverable, needs nothing further from it once generated.
//
// What is taken from the sheet: the 73 topics (37 cosmetics, 36 nails) and,
// per topic, one short "visual seed" line per shape (from the רעיון לוויזואל
// column) — a starting point for a real photoSlot hint, never used verbatim.
// goal and channel are fixed per shape across all 365 rows (verified by
// reading the sheet, not assumed) and live once in SHAPE_META, not repeated
// per topic.
//
// Deliberately NOT taken: טקסט מוכן (the mail-merge copy — the same one
// sentence wrapped in five shells, one row left an unresolved
// "בקליניקה/בסטודיו" placeholder), כותרת (just "{topic} | {shape}", an
// internal label), התאמה אישית / הערת שימוש (boilerplate identical on all
// 365 rows; this product already does both jobs — real variable sources,
// GROUNDING_RULES — better than a static caveat can).
//
//   node --experimental-strip-types scripts/import-topic-bank.mjs

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
// The ESM build's own readFile rejects a path that plain fs.existsSync
// confirms is there (a real quirk of this vendored build, not a typo here);
// require() reads the same file fine.
const require = createRequire(import.meta.url);
const XLSX = require('xlsx');

const SRC = path.resolve(process.cwd(), 'content/imports/templates-365.xlsx');
const OUT = path.resolve(process.cwd(), 'lib/ai/topicBank.ts');

const FIELD_MAP = { 'קוסמטיקאיות': 'cosmetics', 'מניקוריסטיות': 'nails' };
const SHAPE_MAP = {
  'טיפ קצר': 'tip',
  'שאלת קהל': 'audience_question',
  'מיתוס מול מציאות': 'myth_vs_reality',
  'מאחורי הטיפול': 'behind_the_treatment',
  'הזמנה לתור': 'booking_invitation',
};
const SHAPE_ORDER = ['tip', 'audience_question', 'myth_vs_reality', 'behind_the_treatment', 'booking_invitation'];

const wb = XLSX.readFile(SRC);
const rows = XLSX.utils.sheet_to_json(wb.Sheets[wb.SheetNames[0]], { defval: '' });

const byField = { cosmetics: [], nails: [] };
const seen = new Map(); // `${field}::${name}` -> topic object

for (const r of rows) {
  const field = FIELD_MAP[r['תחום']];
  const shape = SHAPE_MAP[r['סוג תבנית']];
  if (!field || !shape) throw new Error(`unrecognised תחום/סוג תבנית: ${JSON.stringify(r)}`);
  const name = String(r['נושא']).trim();
  const key = `${field}::${name}`;
  // Only the topic-anchor half of the visual idea is worth keeping — the
  // shape-specific suffix ("; כותרת גדולה + טיפ אחד" etc.) is regenerated
  // from SHAPE_META at brief-composition time. Verified (not assumed) that
  // the anchor itself never varies by shape within a topic — all five rows
  // of every one of the 73 topics carry the identical anchor string — so
  // this is genuinely one seed per topic, not five.
  const anchor = String(r['רעיון לוויזואל'] || '').split(';')[0].trim();
  let topic = seen.get(key);
  if (!topic) {
    topic = { field, name, visualSeed: anchor };
    seen.set(key, topic);
    byField[field].push(topic);
  } else if (topic.visualSeed !== anchor) {
    throw new Error(`${field} "${name}": visual seed varies by shape (${JSON.stringify(topic.visualSeed)} vs ${JSON.stringify(anchor)}) — the per-topic assumption this script makes no longer holds, switch back to per-shape seeds`);
  }
}

const esc = (s) => JSON.stringify(s);

const lines = [];
lines.push(`// lib/ai/topicBank.ts`);
lines.push(`//`);
lines.push(`// GENERATED by scripts/import-topic-bank.mjs from a source workbook — do`);
lines.push(`// not hand-edit; re-run the script and commit its output instead. The`);
lines.push(`// source itself is not committed (source material, not code); see that`);
lines.push(`// script's own header for what was kept from it and what was left out.`);
lines.push(`//`);
lines.push(`// This is a browsing/prompt-seed list, not copy: buildTopicBrief() (in`);
lines.push(`// this file) turns a (topic, shape) pick into a Hebrew brief for the SAME`);
lines.push(`// pipeline a typed brief goes through (lib/ai/postGenerator.ts's`);
lines.push(`// buildGeneratePrompt) — real, non-formulaic copy written per request,`);
lines.push(`// grounded in her actual services, in her voice, every time.`);
lines.push(``);
lines.push(`import type { FieldKey } from '../businessFields.ts';`);
lines.push(``);
lines.push(`export type ShapeKey = ${SHAPE_ORDER.map(esc).join(' | ')};`);
lines.push(`export type Channel = 'post_story' | 'carousel' | 'reel_post';`);
lines.push(``);
lines.push(`export type ShapeMeta = { label: string; goal: string; channel: Channel };`);
lines.push(``);
lines.push(`// goal and channel are fixed per shape across the whole source sheet`);
lines.push(`// (verified, not assumed — every one of the 365 rows agrees), so they`);
lines.push(`// live once here rather than repeating on all 73 topics.`);
lines.push(`//`);
lines.push(`// channel: 'carousel' (מיתוס מול מציאות) has no real multi-slide`);
lines.push(`// mechanism in this product yet — Template.format is feed45 | story |`);
lines.push(`// square, nothing swipeable. buildTopicBrief() below approximates it: a`);
lines.push(`// single collage-style canvas holding both the myth line and the reality`);
lines.push(`// line, not a real Instagram carousel. Logged, not silently substituted —`);
lines.push(`// see WORK_PLAN.md's "רעיונות לעתיד" for the real-carousel item.`);
lines.push(`export const SHAPE_META: Record<ShapeKey, ShapeMeta> = {`);
for (const s of SHAPE_ORDER) {
  const hebLabel = Object.entries(SHAPE_MAP).find(([, v]) => v === s)[0];
  const row = rows.find((r) => SHAPE_MAP[r['סוג תבנית']] === s);
  lines.push(`  ${s}: { label: ${esc(hebLabel)}, goal: ${esc(row['מטרה'])}, channel: ${esc({ 'פוסט / סטורי': 'post_story', 'קרוסלה': 'carousel', 'רילס / פוסט': 'reel_post' }[row['ערוץ']])} },`);
}
lines.push(`};`);
lines.push(``);
lines.push(`export type Topic = {`);
lines.push(`  id: string;`);
lines.push(`  field: FieldKey;`);
lines.push(`  name: string;`);
lines.push(`  /** One short Hebrew line — a STARTING POINT for a real photoSlot hint`);
lines.push(`   *  or Claude's own imageSubject, the same for every shape (verified: it`);
lines.push(`   *  never varies by shape in the source sheet). Never sent to a client`);
lines.push(`   *  as-is; buildTopicBrief() below folds it into a brief, not a caption. */`);
lines.push(`  visualSeed: string;`);
lines.push(`};`);
lines.push(``);
lines.push(`export const TOPIC_BANK: Topic[] = [`);
for (const field of ['cosmetics', 'nails']) {
  byField[field].forEach((t, i) => {
    const id = `${field}-${String(i + 1).padStart(2, '0')}`;
    lines.push(`  { id: ${esc(id)}, field: ${esc(field)}, name: ${esc(t.name)}, visualSeed: ${esc(t.visualSeed)} },`);
  });
}
lines.push(`];`);
lines.push(``);
lines.push(`export function topicsForField(fields: FieldKey[]): Topic[] {`);
lines.push(`  return TOPIC_BANK.filter((t) => fields.includes(t.field));`);
lines.push(`}`);
lines.push(``);
lines.push(`export function findTopic(id: string): Topic | null {`);
lines.push(`  return TOPIC_BANK.find((t) => t.id === id) || null;`);
lines.push(`}`);
lines.push(``);
lines.push(`/**`);
lines.push(` * A (topic, shape) pick, turned into a Hebrew brief for`);
lines.push(` * lib/ai/postGenerator.ts's buildGeneratePrompt — the exact pipeline a`);
lines.push(` * typed brief goes through, so a topic-bank pick gets a real, freshly`);
lines.push(` * written post, grounded in her actual services and voice, never the`);
lines.push(` * source sheet's one-sentence-in-five-shells text.`);
lines.push(` */`);
lines.push(`export function buildTopicBrief(topic: Topic, shape: ShapeKey): string {`);
lines.push(`  const meta = SHAPE_META[shape];`);
lines.push(`  const seed = topic.visualSeed;`);
lines.push(`  const shapeInstruction: Record<ShapeKey, string> = {`);
lines.push(`    tip: \`טיפ קצר וברור על "\${topic.name}". משהו שאפשר ליישם היום.\`,`);
lines.push(`    audience_question: \`שאלה פתוחה ללקוחות על "\${topic.name}", שמזמינה תגובות בלי לדרוש ידע מוקדם.\`,`);
lines.push(`    myth_vs_reality: \`מיתוס נפוץ על "\${topic.name}" מול המציאות — שתי שורות ברורות, מיתוס ואז מציאות, באותה תמונה (עדיין אין אצלנו קרוסלה אמיתית — קומפוזיציה אחת שמכילה את שתיהן).\`,`);
lines.push(`    behind_the_treatment: \`הצצה אמיתית לאיך זה עובד אצלה, בהקשר של "\${topic.name}" — לא הבטחה, תחושה של להיות שם.\`,`);
lines.push(`    booking_invitation: \`הזמנה לתור סביב "\${topic.name}", חמה ולא לוחצת.\`,`);
lines.push(`  };`);
lines.push(`  return [`);
lines.push(`    shapeInstruction[shape],`);
lines.push(`    \`השראה חזותית (לא טקסט סופי, רק כיוון): \${seed}.\`,`);
lines.push(`    \`מטרת הפוסט: \${meta.goal}.\`,`);
lines.push(`  ].join(' ');`);
lines.push(`}`);
lines.push(``);

fs.writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${OUT}: ${byField.cosmetics.length} cosmetics + ${byField.nails.length} nails topics`);
